#!/usr/bin/env python3
"""Generate ABI constants and reference documentation from the canonical schema."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "spec" / "fpga_linux_abi.yaml"


def canonical_schema() -> tuple[dict, str]:
    data = json.loads(SCHEMA.read_text(encoding="utf-8"))
    encoded = json.dumps(data, sort_keys=True, separators=(",", ":")).encode()
    return data, hashlib.sha256(encoded).hexdigest()


def macro(name: str) -> str:
    return name.upper().replace("-", "_")


def sv(data: dict, digest: str) -> str:
    c = data["constants"]
    lines = ["// Generated by tools/generate_fpga_abi.py. Do not edit.", "`timescale 1ns/1ps",
             "/* verilator lint_off UNUSEDPARAM */",
             "package state_estimator_abi_pkg;"]
    lines.append(f"  localparam longint unsigned CLOCK_HZ = {data['abi']['clock_hz']};")
    for name, value in c.items():
        lines.append(f"  localparam longint unsigned {macro(name)} = {value};")
    lines += [f"  localparam logic [31:0] ABI_HASH_LO = 32'h{digest[:8]};",
              f"  localparam logic [31:0] ABI_HASH_HI = 32'h{digest[8:16]};"]
    for group in ("sensors", "status_flags", "health_values", "control_bits", "irq_bits", "error_bits"):
        for name, value in data[group].items():
            prefix = {"sensors":"SENSOR", "status_flags":"STATUS", "health_values":"HEALTH", "control_bits":"CONTROL", "irq_bits":"IRQ", "error_bits":"ERROR"}[group]
            if group in ("status_flags", "control_bits", "irq_bits", "error_bits"):
                lines.append(f"  localparam logic [31:0] {prefix}_{macro(name)} = 32'h{1 << value:08X};")
            else:
                lines.append(f"  localparam int unsigned {prefix}_{macro(name)} = {value};")
    for reg in data["registers"]:
        lines.append(f"  localparam logic [15:0] REG_{reg['name']} = 16'h{reg['offset']:04X};")
    for name, value in data["banks"].items():
        lines.append(f"  localparam logic [15:0] BANK_{macro(name)} = 16'h{value:04X};")
    for group, prefix in (("dma_bank_registers", "DMA_REG"), ("r5_bank_registers", "R5_REG"), ("replay_bank_registers", "REPLAY_REG"), ("sensor_bank_registers", "SENSOR_REG")):
        for reg in data[group]:
            lines.append(f"  localparam logic [7:0] {prefix}_{reg['name']} = 8'h{reg['offset']:02X};")
    lines += ["endpackage", "/* verilator lint_on UNUSEDPARAM */", ""]
    return "\n".join(lines)


def rust(data: dict, digest: str) -> str:
    c = data["constants"]
    lines = ["// Generated by tools/generate_fpga_abi.py. Do not edit.",
             f"pub const ABI_MAJOR: u16 = {data['abi']['major']};",
             f"pub const ABI_MINOR: u16 = {data['abi']['minor']};",
             f"pub const CLOCK_HZ: u64 = {data['abi']['clock_hz']};",
             f"pub const ABI_HASH_HEX: &str = \"{digest}\";",
             f"pub const ABI_HASH_LO: u32 = 0x{digest[:8]};",
             f"pub const ABI_HASH_HI: u32 = 0x{digest[8:16]};",
             f"pub const ABI_HASH_U64: u64 = ((ABI_HASH_HI as u64) << 32) | ABI_HASH_LO as u64;"]
    for name, value in c.items():
        typ = "usize" if "bytes" in name or "count" in name or "alignment" in name else "u64"
        lines.append(f"pub const {macro(name)}: {typ} = {value};")
    for region in data["address_regions"]:
        lines += [f"pub const {macro(region['name'])}_BASE: u64 = 0x{region['base']:08X};",
                  f"pub const {macro(region['name'])}_SIZE: usize = {region['size']};"]
    for group in ("sensors", "status_flags", "health_values", "control_bits", "irq_bits", "error_bits"):
        for name, value in data[group].items():
            prefix = {"sensors":"SENSOR", "status_flags":"STATUS", "health_values":"HEALTH", "control_bits":"CONTROL", "irq_bits":"IRQ", "error_bits":"ERROR"}[group]
            if group in ("status_flags", "control_bits", "irq_bits", "error_bits"):
                lines.append(f"pub const {prefix}_{macro(name)}: u32 = 1u32 << {value};")
            else:
                lines.append(f"pub const {prefix}_{macro(name)}: u8 = {value};")
    for reg in data["registers"]:
        lines.append(f"pub const REG_{reg['name']}: usize = 0x{reg['offset']:04X};")
    for group, prefix in (("dma_bank_registers", "DMA_REG"), ("r5_bank_registers", "R5_REG"), ("replay_bank_registers", "REPLAY_REG"), ("sensor_bank_registers", "SENSOR_REG")):
        for reg in data[group]:
            lines.append(f"pub const {prefix}_{reg['name']}: usize = 0x{reg['offset']:02X};")
    return "\n".join(lines) + "\n"


def python(data: dict, digest: str) -> str:
    lines = ["# Generated by tools/generate_fpga_abi.py. Do not edit.",
             f"ABI_MAJOR = {data['abi']['major']}", f"ABI_MINOR = {data['abi']['minor']}",
             f"ABI_HASH_HEX = \"{digest}\"", f"ABI_HASH_LO = 0x{digest[:8]}",
             f"ABI_HASH_HI = 0x{digest[8:16]}", "ABI_HASH_U64 = (ABI_HASH_HI << 32) | ABI_HASH_LO"]
    lines.append(f"CLOCK_HZ = {data['abi']['clock_hz']}")
    for name, value in data["constants"].items():
        lines.append(f"{macro(name)} = {value}")
    for group in ("sensors", "status_flags", "health_values", "control_bits", "irq_bits", "error_bits"):
        for name, value in data[group].items():
            prefix = {"sensors":"SENSOR", "status_flags":"STATUS", "health_values":"HEALTH", "control_bits":"CONTROL", "irq_bits":"IRQ", "error_bits":"ERROR"}[group]
            actual = 1 << value if group in ("status_flags", "control_bits", "irq_bits", "error_bits") else value
            lines.append(f"{prefix}_{macro(name)} = {actual}")
    for reg in data["registers"]:
        lines.append(f"REG_{reg['name']} = 0x{reg['offset']:04X}")
    for group, prefix in (("dma_bank_registers", "DMA_REG"), ("r5_bank_registers", "R5_REG"), ("replay_bank_registers", "REPLAY_REG"), ("sensor_bank_registers", "SENSOR_REG")):
        for reg in data[group]:
            lines.append(f"{prefix}_{reg['name']} = 0x{reg['offset']:02X}")
    return "\n".join(lines) + "\n"


def markdown(data: dict, digest: str) -> str:
    rows = ["# FPGA-to-Linux ABI v1", "", "This file is generated from `spec/fpga_linux_abi.yaml`. Do not edit it directly.", "",
            f"Schema SHA-256: `{digest}`", "", "## Address map", "", "| Region | Base | Size |", "| --- | ---: | ---: |"]
    for r in data["address_regions"]:
        rows.append(f"| {r['name']} | `0x{r['base']:08X}` | {r['size'] // 1024} KiB |")
    rows += ["", "## Core registers", "", "All accesses are aligned, little-endian 32-bit AXI-Lite transactions.", "", "| Offset | Register | Access |", "| ---: | --- | --- |"]
    for r in data["registers"]:
        rows.append(f"| `0x{r['offset']:04X}` | `{r['name']}` | {r['access'].upper()} |")
    for title, group in (("DMA mirror bank at 0x0100", "dma_bank_registers"), ("R5F ring bank at 0x0200", "r5_bank_registers"), ("Replay bank at 0x0300", "replay_bank_registers"), ("Per-sensor bank", "sensor_bank_registers")):
        rows += ["", f"## {title}", "", "| Relative offset | Register | Access |", "| ---: | --- | --- |"]
        for r in data[group]:
            rows.append(f"| `0x{r['offset']:02X}` | `{r['name']}` | {r['access'].upper()} |")
    rows += ["", "## Sensor identifiers", "", "| ID | Name |", "| ---: | --- |"]
    for name, value in sorted(data["sensors"].items(), key=lambda x: x[1]):
        rows.append(f"| {value} | `{name}` |")
    rows += ["", "## Common record", "", f"Header: {data['constants']['record_header_bytes']} bytes. Maximum payload: {data['constants']['max_payload_bytes']} bytes. Records are 8-byte aligned and never cross a DMA block.", "", "| Offset | Type | Field |", "| ---: | --- | --- |"]
    for name, typ, offset in data["common_record_fields"]:
        rows.append(f"| {offset} | `{typ}` | `{name}` |")
    rows += ["", "## DMA block", "", f"The coherent ring contains {data['constants']['dma_block_count']} blocks of {data['constants']['dma_block_bytes']} bytes.", "", "| Offset | Type | Field |", "| ---: | --- | --- |"]
    for name, typ, offset in data["dma_block_fields"]:
        rows.append(f"| {offset} | `{typ}` | `{name}` |")
    rows += ["", "CRC32C uses reflected polynomial `0x82F63B78`, initial value `0xFFFFFFFF`, and final XOR `0xFFFFFFFF`.", ""]
    return "\n".join(rows)


def crc32c(value: bytes) -> int:
    crc = 0xFFFFFFFF
    for byte in value:
        crc ^= byte
        for _ in range(8):
            crc = (crc >> 1) ^ (0x82F63B78 if crc & 1 else 0)
    return crc ^ 0xFFFFFFFF


def golden_fixtures(data: dict, digest: str) -> dict[Path, bytes]:
    c = data["constants"]
    payload = bytes.fromhex("080003000801020304050607")
    total = (c["record_header_bytes"] + len(payload) + 7) & ~7
    header = bytearray(struct.pack("<IBBHHHIQQIIII", c["record_magic"], 1, 6, 48, total, len(payload), 0x01020304, 123456789, 123457989, 1, 0, crc32c(payload), 0))
    struct.pack_into("<I", header, 44, crc32c(header))
    record = bytes(header) + payload + bytes(total - 48 - len(payload))
    valid = 64 + len(record)
    block_header = bytearray(struct.pack("<IHHIIHHIIIIIQQII", c["block_magic"], data["abi"]["major"], 64, 7, 0, valid, 1, 1 << 6, 0, 3, 0x12345678, 0, 123456789, 123456789, crc32c(record), 0))
    struct.pack_into("<I", block_header, 60, crc32c(block_header))
    block = bytes(block_header) + record + bytes(c["dma_block_bytes"] - valid)
    replay = struct.pack("<IHHQ", c["injection_magic"], 1, 16, 5000) + record
    blobs = {"common_record_v1.bin": record, "dma_block_v1.bin": block, "replay_item_v1.bin": replay}
    manifest = {
        "abi_hash": digest,
        "fixtures": {name: {"bytes": len(value), "sha256": hashlib.sha256(value).hexdigest()} for name, value in blobs.items()},
    }
    result = {ROOT / "spec/golden" / name: value for name, value in blobs.items()}
    result[ROOT / "spec/golden/manifest.json"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    return result


def outputs(data: dict, digest: str) -> dict[Path, str | bytes]:
    result: dict[Path, str | bytes] = {
        ROOT / "src/rtl/generated/state_estimator_abi_pkg.sv": sv(data, digest),
        ROOT / "linux/rust/se-abi/src/generated.rs": rust(data, digest),
        ROOT / "sim/src/digital_twin/generated_abi.py": python(data, digest),
        ROOT / "docs/fpga-linux-abi.md": markdown(data, digest),
    }
    result.update(golden_fixtures(data, digest))
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data, digest = canonical_schema()
    stale = []
    for path, content in outputs(data, digest).items():
        encoded = content.encode() if isinstance(content, str) else content
        if args.check:
            if not path.exists() or path.read_bytes() != encoded:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(encoded)
    if stale:
        print("generated ABI files are stale: " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    print(f"ABI v{data['abi']['major']}.{data['abi']['minor']} schema {digest[:16]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
